#!/usr/bin/env bash
#
# applenix installer — stage 1, for any Apple Silicon Mac.
#
# Run this as root from the nixos-apple-silicon USB installer:
#
#   curl -fsSL https://raw.githubusercontent.com/teoscloud/teonix/main/hosts/applenix/install.sh | bash
#
# It is idempotent: re-run the exact same command after any failure and the
# steps that already succeeded are skipped.
#
# Stage 1 deliberately does NOT use the teonix flake. It generates a plain
# /mnt/etc/nixos/configuration.nix against the ISO's own nixpkgs and the ISO's
# own apple-silicon-support module, so nixos-install copies the Asahi kernel
# out of the installer instead of rebuilding it (which OOMs in the installer,
# and there is no upstream binary cache for it).
#
# Stage 2 (the teonix Hyprland rice) runs from the booted Mac:
#   /etc/applenix/stage2.sh
#
# -E so the ERR trap below also fires for failures inside functions.
set -Eeuo pipefail

readonly VERSION=9
readonly SELF="applenix-install"
readonly CURL_CMD="curl -fsSL https://raw.githubusercontent.com/teoscloud/teonix/main/hosts/applenix/install.sh | bash"

readonly STEPS=(
  detect
  net
  disk
  format
  mount
  firmware
  config
  install
  stage2
  summary
)

# Everything below can be overridden from the environment.
TARGET_USER="${TARGET_USER:-teodor}"
TARGET_HOST="${TARGET_HOST:-applenix}"
TEONIX_REPO="${TEONIX_REPO:-https://github.com/teoscloud/teonix.git}"
TEONIX_DIR="${TEONIX_DIR:-/home/${TARGET_USER}/teonix}"
CHARGE_LIMIT="${CHARGE_LIMIT:-80}"
FACTS="${FACTS:-/tmp/applenix-facts}"

readonly ROOT_LABEL=nixos
# TARGET=/ lets you regenerate stage2.sh on an already-booted applenix:
#   sudo TARGET=/ bash install.sh run stage2
TARGET="${TARGET:-/mnt}"
NIXOS_DIR="${TARGET%/}/etc/nixos"
FW_DIR="${NIXOS_DIR}/firmware"
STAGE2="${TARGET%/}/etc/applenix/stage2.sh"
readonly CONFIG_MARKER="# generated by ${SELF} v"

# ---------------------------------------------------------------- output ----

say() { printf '%s\n' "$*"; }
info() { printf '       %s\n' "$*"; }
ok() { printf '[ ok ] %s\n' "$*"; }
skip() { printf '[skip] %s\n' "$*"; }
runmsg() { printf '[ run] %s\n' "$*"; }
warn() { printf '[warn] %s\n' "$*" >&2; }
die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

CURRENT_STEP=""

on_err() {
  local code=$?
  [[ -n $CURRENT_STEP ]] || exit "$code"
  printf '\n' >&2
  printf 'error: step "%s" failed (exit %d)\n' "$CURRENT_STEP" "$code" >&2
  printf '       fix the cause and re-run the same command; finished steps are skipped:\n' >&2
  printf '         %s\n' "$CURL_CMD" >&2
  exit "$code"
}
trap on_err ERR

need_root() { [[ $(id -u) -eq 0 ]] || die "run as root first: sudo su"; }

# Prompts read the tty directly so `curl … | bash` stays interactive.
confirm() {
  local question=$1 answer
  [[ ${YES:-0} == 1 ]] && return 0
  [[ -r /dev/tty ]] || die "no tty available for confirmation — re-run with YES=1"
  printf '%s [type YES]: ' "$question" >/dev/tty
  read -r answer </dev/tty || die "aborted"
  [[ $answer == YES ]] || die "aborted"
}

# ----------------------------------------------------------------- facts ----

fact_set() {
  local key=$1 value=$2 tmp
  mkdir -p "$(dirname "$FACTS")"
  : >>"$FACTS"
  tmp=$(mktemp)
  grep -v "^${key}=" "$FACTS" >"$tmp" || true
  printf '%s=%s\n' "$key" "$value" >>"$tmp"
  LC_ALL=C sort -o "$FACTS" "$tmp"
  rm -f "$tmp"
}

fact_get() {
  local key=$1 value
  [[ -f $FACTS ]] || return 1
  value=$(sed -n "s/^${key}=//p" "$FACTS" | tail -n1)
  [[ -n $value ]] || return 1
  printf '%s\n' "$value"
}

fact_or() {
  fact_get "$1" 2>/dev/null || printf '%s\n' "$2"
}

# ------------------------------------------------------------- detection ----

# Device-tree properties are NUL-terminated.
dt_string() {
  [[ -e $1 ]] || return 1
  tr -d '\0' <"$1"
}

dt_list() {
  [[ -e $1 ]] || return 1
  tr '\0' ' ' <"$1"
}

esp_partuuid() {
  dt_string /proc/device-tree/chosen/asahi,efi-system-partition
}

esp_dev() {
  local uuid
  uuid=$(esp_partuuid) || return 1
  [[ -n $uuid ]] || return 1
  printf '/dev/disk/by-partuuid/%s\n' "$uuid"
}

# The ESP the Asahi installer made for us identifies the disk to install on.
# Never assume /dev/nvme0n1: Mac Pro and external-boot setups differ.
detect_disk() {
  local esp resolved parent
  if [[ -n ${DISK:-} ]]; then
    printf '%s\n' "$DISK"
    return 0
  fi
  esp=$(esp_dev) || return 1
  resolved=$(readlink -f "$esp" 2>/dev/null) || return 1
  [[ -b $resolved ]] || return 1
  parent=$(lsblk -npo PKNAME "$resolved" 2>/dev/null | head -n1)
  [[ -n $parent ]] || return 1
  printf '%s\n' "$parent"
}

# A battery means a laptop. Cheaper and more future-proof than a model table.
detect_chassis() {
  local ps
  for ps in /sys/class/power_supply/*; do
    [[ -e $ps/type ]] || continue
    [[ $(cat "$ps/type" 2>/dev/null) == Battery ]] && {
      printf 'laptop\n'
      return 0
    }
  done
  printf 'desktop\n'
}

detect_touchbar() {
  local card driver
  if [[ -n ${TOUCHBAR:-} ]]; then
    printf '%s\n' "$TOUCHBAR"
    return 0
  fi
  for card in /sys/class/drm/card*; do
    [[ -e $card/device/driver ]] || continue
    driver=$(basename "$(readlink -f "$card/device/driver")")
    [[ $driver == appletbdrm ]] && {
      printf 'yes\n'
      return 0
    }
  done
  [[ -e /sys/class/backlight/appletb_backlight ]] && {
    printf 'yes\n'
    return 0
  }
  printf 'no\n'
}

detect_displays() {
  local connector name out=()
  for connector in /sys/class/drm/card*-*; do
    [[ -r $connector/status ]] || continue
    [[ $(cat "$connector/status" 2>/dev/null) == connected ]] || continue
    name=${connector##*/}
    out+=("${name#*-}")
  done
  ((${#out[@]})) || return 1
  local IFS=,
  printf '%s\n' "${out[*]}"
}

detect_wifi() {
  local iface out=()
  for iface in /sys/class/net/*; do
    [[ -d $iface/wireless ]] || continue
    out+=("${iface##*/}")
  done
  ((${#out[@]})) && printf '%s\n' "${out[0]}"
}

detect_ram_mb() { awk '/^MemTotal:/ { printf "%d\n", $2 / 1024 }' /proc/meminfo; }

detect_release() { nixos-version 2>/dev/null | cut -d. -f1,2; }

# Kernel and rust builds are memory-hungry; too many parallel jobs OOM an 8 GB
# Mac, too few waste an M4 Max. Derive from RAM instead of hardcoding.
derive_max_jobs() {
  local gb=$1
  if ((gb <= 8)); then
    printf '1\n'
  elif ((gb <= 16)); then
    printf '2\n'
  else
    printf '4\n'
  fi
}

# The stage 2 kernel build wants far more than an 8 GB Mac has. Swap is cheap
# on disk and is the difference between "slow" and "Killed".
derive_swap_mb() {
  local gb=$1
  [[ -n ${SWAP_SIZE:-} ]] && {
    printf '%s\n' "$SWAP_SIZE"
    return 0
  }
  if ((gb <= 8)); then
    printf '16384\n'
  elif ((gb <= 16)); then
    printf '12288\n'
  else
    printf '8192\n'
  fi
}

# Parallelism inside one derivation. Peak memory scales with this, and rustc on
# the Asahi kernel is heavy, so a small Mac must not use every core.
derive_build_cores() {
  local gb=$1
  [[ -n ${BUILD_CORES:-} ]] && {
    printf '%s\n' "$BUILD_CORES"
    return 0
  }
  if ((gb <= 8)); then
    printf '2\n'
  elif ((gb <= 16)); then
    printf '4\n'
  else
    printf '0\n' # 0 = all cores
  fi
}

# ------------------------------------------------------------ disk tools ----

reread_pt() {
  local disk=$1
  partprobe "$disk" 2>/dev/null || blockdev --rereadpt "$disk" 2>/dev/null || true
  udevadm settle 2>/dev/null || sleep 1
}

list_parts() {
  lsblk -nrpo NAME,TYPE "$1" 2>/dev/null | awk '$2 == "part" { print $1 }'
}

# 0fc63daf-… is the GPT GUID behind sgdisk's 8300 "Linux filesystem" code.
list_linux_parts() {
  lsblk -nrpo NAME,TYPE,PARTTYPE "$1" 2>/dev/null \
    | awk 'tolower($3) == "0fc63daf-8483-4772-8e79-3d69d8477de4" && $2 == "part" { print $1 }'
}

labeled_root() {
  local dev="/dev/disk/by-label/${ROOT_LABEL}"
  [[ -b $dev ]] || return 1
  readlink -f "$dev"
}

find_fwextract() {
  local candidate
  if command -v asahi-fwextract >/dev/null 2>&1; then
    command -v asahi-fwextract
    return 0
  fi
  for candidate in /nix/store/*-asahi-fwextract*/bin/asahi-fwextract; do
    [[ -x $candidate ]] && {
      printf '%s\n' "$candidate"
      return 0
    }
  done
  return 1
}

# ------------------------------------------------------------- probes -------
# Each probe answers "is this step already satisfied?" from live system state,
# so a half-finished run resumes correctly instead of trusting a state file.

probe_detect() { [[ -s $FACTS ]]; }

probe_net() {
  ping -c1 -W3 cache.nixos.org >/dev/null 2>&1 || ping -c1 -W3 github.com >/dev/null 2>&1
}

probe_disk() {
  local root
  root=$(fact_get ROOT_PART 2>/dev/null) || return 1
  [[ -b $root ]]
}

probe_format() {
  local root
  root=$(fact_get ROOT_PART 2>/dev/null) || return 1
  [[ $(blkid -o value -s TYPE "$root" 2>/dev/null) == ext4 ]]
}

probe_mount() {
  findmnt -M "$TARGET" >/dev/null 2>&1 && findmnt -M "$TARGET/boot" >/dev/null 2>&1
}

probe_firmware() { [[ -s $FW_DIR/firmware.cpio ]]; }

probe_config() {
  [[ -f $NIXOS_DIR/configuration.nix ]] || return 1
  [[ -f $NIXOS_DIR/hardware-configuration.nix ]] || return 1
  [[ -d $NIXOS_DIR/apple-silicon-support ]] || return 1
  grep -qF "$CONFIG_MARKER" "$NIXOS_DIR/configuration.nix"
}

probe_install() { [[ -e $TARGET/nix/var/nix/profiles/system ]]; }

probe_stage2() { [[ -x $STAGE2 ]]; }

probe_summary() { return 1; }

# -------------------------------------------------------------- steps -------

step_detect() {
  local disk esp chassis touchbar displays wifi ram_mb ram_gb cores release

  [[ -e /proc/device-tree/chosen/asahi,efi-system-partition ]] \
    || die "no asahi,efi-system-partition in the device tree — this is not the nixos-apple-silicon installer, or the Asahi UEFI environment was never installed"

  esp=$(esp_dev) || die "could not resolve the ESP from the device tree"
  disk=$(detect_disk) || die "could not derive the target disk from the ESP — set DISK=/dev/nvme0n1"
  chassis=$(detect_chassis)
  touchbar=$(detect_touchbar)
  displays=$(detect_displays || true)
  wifi=$(detect_wifi || true)
  ram_mb=$(detect_ram_mb)
  ram_gb=$((ram_mb / 1024))
  cores=$(nproc)
  release=$(detect_release)

  [[ -n $release ]] || die "could not read nixos-version"

  fact_set MODEL "$(dt_string /proc/device-tree/model 2>/dev/null || echo unknown)"
  fact_set COMPATIBLE "$(dt_list /proc/device-tree/compatible 2>/dev/null || echo unknown)"
  fact_set CHASSIS "$chassis"
  fact_set DISK "$disk"
  fact_set ESP "$esp"
  fact_set TOUCHBAR "$touchbar"
  fact_set DISPLAYS "${displays:-unknown}"
  fact_set WIFI "${wifi:-none}"
  fact_set RAM_MB "$ram_mb"
  fact_set CORES "$cores"
  fact_set MAX_JOBS "$(derive_max_jobs "$ram_gb")"
  fact_set SWAP_MB "$(derive_swap_mb "$ram_gb")"
  fact_set BUILD_CORES "$(derive_build_cores "$ram_gb")"
  fact_set RELEASE "$release"
  fact_set TARGET_USER "$TARGET_USER"
  fact_set TARGET_HOST "$TARGET_HOST"
  fact_set TEONIX_REPO "$TEONIX_REPO"
  fact_set TEONIX_DIR "$TEONIX_DIR"
  fact_set CHARGE_LIMIT "$CHARGE_LIMIT"
  [[ -n ${ISO_LAYOUT:-} ]] && fact_set ISO_LAYOUT "$ISO_LAYOUT" || true
  [[ -n ${M1N1_EXTRA:-} ]] && fact_set M1N1_EXTRA "$M1N1_EXTRA" || true
  [[ -n ${PKGS_SYSTEM:-} ]] && fact_set PKGS_SYSTEM "$PKGS_SYSTEM" || true

  ok "detect"
  info "model      $(fact_or MODEL unknown)"
  info "compatible $(fact_or COMPATIBLE unknown)"
  info "chassis    $chassis"
  info "disk       $disk"
  info "esp        $esp"
  info "memory     ${ram_gb} GiB, ${cores} cores -> max-jobs $(fact_or MAX_JOBS 1)"
  info "stage 2    swap $(fact_or SWAP_MB 8192) MiB, build cores $(fact_or BUILD_CORES 2)"
  info "touch bar  $touchbar"
  info "displays   ${displays:-unknown}"
  info "wifi       ${wifi:-none}"
  info "release    $release"
}

step_net() {
  if probe_net; then
    ok "net — already online"
  else
    cat <<'EOF'

No network. Connect Wi-Fi from the installer first:

  iwctl
  [iwd]# station wlan0 scan
  [iwd]# station wlan0 connect YOUR_SSID
  [iwd]# station wlan0 show
  [iwd]# exit

Ethernet over a USB dongle also works. Then re-run this installer.
EOF
    die "no network"
  fi
  systemctl restart systemd-timesyncd 2>/dev/null || true
}

step_disk() {
  local disk root existing=() before=() after=() created=()

  disk=$(fact_get DISK) || die "no disk recorded — run the detect step first"
  [[ -b $disk ]] || die "$disk is not a block device"

  if [[ -n ${ROOT_PART:-} ]]; then
    [[ -b $ROOT_PART ]] || die "ROOT_PART=$ROOT_PART is not a block device"
    fact_set ROOT_PART "$ROOT_PART"
    ok "disk — using ROOT_PART=$ROOT_PART"
    return 0
  fi

  if root=$(labeled_root); then
    fact_set ROOT_PART "$root"
    ok "disk — reusing existing '${ROOT_LABEL}' partition $root"
    return 0
  fi

  mapfile -t existing < <(list_linux_parts "$disk")
  if ((${#existing[@]} == 1)); then
    fact_set ROOT_PART "${existing[0]}"
    ok "disk — reusing existing Linux partition ${existing[0]}"
    return 0
  fi
  if ((${#existing[@]} > 1)); then
    die "several Linux partitions on $disk (${existing[*]}) — choose one with ROOT_PART=/dev/…"
  fi

  say ""
  sgdisk -p "$disk" || true
  cat <<EOF

About to create ONE new partition filling the free space on $disk.
macOS, the iBoot container, the ESP and the Recovery container are untouched.
EOF
  confirm "Create the NixOS root partition on $disk?"

  mapfile -t before < <(list_parts "$disk")
  sgdisk "$disk" -n "0:0:0" -t "0:8300" -c "0:${ROOT_LABEL}" -s
  reread_pt "$disk"
  mapfile -t after < <(list_parts "$disk")

  mapfile -t created < <(
    comm -13 \
      <(printf '%s\n' "${before[@]+${before[@]}}" | LC_ALL=C sort) \
      <(printf '%s\n' "${after[@]+${after[@]}}" | LC_ALL=C sort)
  )

  for root in "${created[@]+${created[@]}}"; do
    [[ -b $root ]] || continue
    fact_set ROOT_PART "$root"
    ok "disk — created $root"
    return 0
  done

  die "sgdisk reported success but no new partition appeared — inspect 'sgdisk -p $disk' and re-run with ROOT_PART=/dev/…"
}

step_format() {
  local root fstype
  root=$(fact_get ROOT_PART) || die "no root partition recorded — run the disk step first"
  fstype=$(blkid -o value -s TYPE "$root" 2>/dev/null || true)

  if [[ $fstype == ext4 && ${FORMAT:-0} != 1 ]]; then
    skip "format — $root is already ext4 (FORMAT=1 to erase it)"
    return 0
  fi
  if [[ -n $fstype && ${FORMAT:-0} != 1 ]]; then
    die "$root already holds a '$fstype' filesystem — set FORMAT=1 to erase it"
  fi

  confirm "Format $root as ext4? This erases that partition only."
  mkfs.ext4 -F -L "$ROOT_LABEL" "$root"
  ok "format — $root is ext4, label ${ROOT_LABEL}"
}

step_mount() {
  local root esp
  root=$(fact_get ROOT_PART) || die "no root partition recorded — run the disk step first"

  findmnt -M "$TARGET" >/dev/null 2>&1 || mount "$root" "$TARGET"

  mkdir -p "$TARGET/boot"
  if ! findmnt -M "$TARGET/boot" >/dev/null 2>&1; then
    esp=$(esp_dev) || die "could not resolve the ESP"
    mount "$esp" "$TARGET/boot"
  fi

  ok "mount — $(findmnt -no SOURCE "$TARGET") on $TARGET, $(findmnt -no SOURCE "$TARGET/boot") on $TARGET/boot"
}

# Wi-Fi, Bluetooth, camera and the ambient light sensor need Apple's
# non-redistributable firmware. The ESP carries it as a raw asahi/ tree; the
# cpio archive the module wants is produced by asahi-fwextract, exactly like
# the ISO does in its own boot.postBootCommands.
step_firmware() {
  local cpio="$FW_DIR/firmware.cpio" fwextract

  if [[ -s $cpio && ${FORCE:-0} != 1 ]]; then
    skip "firmware — $cpio already present"
    return 0
  fi

  mkdir -p "$FW_DIR"

  if [[ -s $TARGET/boot/vendorfw/firmware.cpio ]]; then
    cp -f "$TARGET/boot/vendorfw/firmware.cpio" "$cpio"
    ok "firmware — copied from the ESP's vendorfw/"
    return 0
  fi

  if [[ ! -d $TARGET/boot/asahi ]]; then
    warn "no vendorfw/ or asahi/ on the ESP — Wi-Fi, Bluetooth and the camera will not work"
    warn "boot macOS, run 'curl https://alx.sh | sh', pick 'Rebuild vendor firmware package', then re-run this step"
    rmdir "$FW_DIR" 2>/dev/null || true
    return 0
  fi

  fwextract=$(find_fwextract) \
    || die "asahi-fwextract is not in this installer's store — copy vendorfw/firmware.cpio to $cpio by hand and re-run"

  "$fwextract" "$TARGET/boot/asahi" "$FW_DIR"
  [[ -s $cpio ]] || die "asahi-fwextract did not produce $cpio"
  ok "firmware — extracted from the ESP's asahi/ with $(basename "$fwextract")"
}

step_config() {
  local iso_module=/etc/nixos/apple-silicon-support

  [[ -d $iso_module ]] \
    || die "$iso_module is missing — this ISO is not from nixos-apple-silicon, so its Asahi kernel cannot be reused"

  mkdir -p "$NIXOS_DIR"
  nixos-generate-config --root "$TARGET"

  # The ISO plants its own apple-silicon-support in /etc/nixos. Copying it
  # (rather than pinning a flake input) is what keeps the kernel identical to
  # the one already built into this installer.
  rm -rf "$NIXOS_DIR/apple-silicon-support"
  cp -r "$iso_module" "$NIXOS_DIR/apple-silicon-support"
  chmod -R u+w "$NIXOS_DIR/apple-silicon-support"

  write_configuration >"$NIXOS_DIR/configuration.nix"
  cp -f "$FACTS" "$NIXOS_DIR/applenix-facts.txt"

  ok "config — wrote $NIXOS_DIR/configuration.nix against the ISO's nixpkgs and apple-silicon-support"
}

step_install() {
  if probe_install && [[ ${FORCE:-0} != 1 ]]; then
    skip "install — a system profile already exists under $TARGET/nix (FORCE=1 to install again)"
    return 0
  fi

  say ""
  info "running nixos-install; the kernel is copied from the installer, so this"
  info "should take minutes rather than hours"
  say ""

  nixos-install --root "$TARGET" --no-root-password

  ok "install — stage 1 system installed"
}

step_stage2() {
  mkdir -p "$(dirname "$STAGE2")"
  write_stage2 >"$STAGE2"
  chmod +x "$STAGE2"
  ok "stage2 — installed ${STAGE2#"${TARGET%/}"} on the new system"
}

step_summary() {
  local user host displays
  user=$(fact_or TARGET_USER "$TARGET_USER")
  host=$(fact_or TARGET_HOST "$TARGET_HOST")
  displays=$(fact_or DISPLAYS unknown)

  cat <<EOF

──────────────────────────────────────────────────────────────
 Stage 1 done: ${host} is installed and bootable.
──────────────────────────────────────────────────────────────

  reboot          (then unplug the USB stick)

Log in as ${user} / ${user} on the text console, then:

  passwd
  /etc/applenix/stage2.sh

Stage 2 clones teonix, copies this Mac's hardware config and Asahi
firmware into the flake, and switches to the #applenix Hyprland rice.
It does not need --impure.

Detected displays: ${displays}
If Hyprland or Quickshell come up on the wrong output, adjust
home/hosts/applenix/dotfiles/config/hypr/hyprland.conf and
home/hosts/applenix/dotfiles/config/quickshell/Globals.qml.
EOF
}

# ------------------------------------------- generated stage 1 config -------

write_configuration() {
  local user host release ram_gb max_jobs cores chassis touchbar
  local fw_fragment="" touchbar_fragment="" battery_fragment=""
  local m1n1_fragment="" modprobe_fragment="" pkgs_system_fragment=""

  user=$(fact_or TARGET_USER "$TARGET_USER")
  host=$(fact_or TARGET_HOST "$TARGET_HOST")
  release=$(fact_get RELEASE)
  ram_gb=$(($(fact_or RAM_MB 4096) / 1024))
  max_jobs=$(fact_or MAX_JOBS 1)
  cores=$(fact_or CORES 4)
  chassis=$(fact_or CHASSIS desktop)
  touchbar=$(fact_or TOUCHBAR no)

  if [[ -s $FW_DIR/firmware.cpio ]]; then
    fw_fragment="  hardware.asahi.extractPeripheralFirmware = true;
  hardware.asahi.peripheralFirmwareDirectory = ./firmware;"
  else
    fw_fragment="  # No firmware.cpio was found on the ESP; Wi-Fi and the camera stay dark
  # until you rebuild the vendor firmware package from macOS.
  hardware.asahi.extractPeripheralFirmware = false;"
  fi

  if [[ $touchbar == yes ]]; then
    touchbar_fragment="
  hardware.apple.touchBar.enable = true;"
  fi

  if [[ $chassis == laptop ]]; then
    battery_fragment="
  services.udev.extraRules = ''
    SUBSYSTEM==\"power_supply\", KERNEL==\"macsmc-battery\", ATTR{charge_control_end_threshold}=\"$(fact_or CHARGE_LIMIT "$CHARGE_LIMIT")\"
  '';"
  fi

  if [[ -n $(fact_get M1N1_EXTRA 2>/dev/null || true) ]]; then
    m1n1_fragment="
  boot.m1n1ExtraOptions = \"$(fact_get M1N1_EXTRA)\";"
  fi

  if [[ -n $(fact_get ISO_LAYOUT 2>/dev/null || true) ]]; then
    modprobe_fragment="
  boot.extraModprobeConfig = ''
    options hid_apple iso_layout=$(fact_get ISO_LAYOUT)
  '';"
  fi

  if [[ -n $(fact_get PKGS_SYSTEM 2>/dev/null || true) ]]; then
    pkgs_system_fragment="
  # Matches the build platform of a cross-built installer ISO so its
  # prebuilt Asahi kernel is reused instead of rebuilt.
  hardware.asahi.pkgsSystem = \"$(fact_get PKGS_SYSTEM)\";"
  fi

  cat <<EOF
${CONFIG_MARKER}${VERSION} on $(date -u '+%Y-%m-%d %H:%M UTC')
#
# Stage 1: minimal console system for ${host}.
#
# This is deliberately a plain configuration.nix, not a flake. It builds
# against the ISO's nixpkgs and the apple-silicon-support copied out of the
# ISO, so nixos-install reuses the installer's Asahi kernel instead of
# rebuilding it. Do not "upgrade" this to the teonix flake — that is what
# stage 2 (/etc/applenix/stage2.sh) is for.
#
# Detected: $(fact_or MODEL unknown) / $(fact_or COMPATIBLE unknown)
# ${ram_gb} GiB RAM, ${cores} cores, ${chassis}
{ config, lib, pkgs, ... }:

{
  imports = [
    ./hardware-configuration.nix
    ./apple-silicon-support
  ];

  hardware.asahi.enable = true;
  hardware.asahi.setupAsahiSound = true;
${fw_fragment}${pkgs_system_fragment}

