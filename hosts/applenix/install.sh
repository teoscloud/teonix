# ------------------------------------------------ generated stage 2 ---------

write_stage2() {
  cat <<EOF
#!/usr/bin/env bash
#
# applenix stage 2 — switch this Mac from the stage 1 console system to the
# teonix #applenix Hyprland rice. Generated by ${SELF} v${VERSION}.
#
# Run it as ${TARGET_USER} (not root), from a booted applenix:
#   /etc/applenix/stage2.sh
#
# Safe to re-run: every step checks its own result first.
#
set -euo pipefail

REPO="\${TEONIX_REPO:-$(fact_or TEONIX_REPO "$TEONIX_REPO")}"
DIR="\${TEONIX_DIR:-$(fact_or TEONIX_DIR "$TEONIX_DIR")}"
FACTS=/etc/nixos/applenix-facts.txt
HOST_DIR="\$DIR/hosts/applenix"
SWAPFILE=/swapfile

say() { printf '%s\\n' "\$*"; }
ok() { printf '[ ok ] %s\\n' "\$*"; }
skip() { printf '[skip] %s\\n' "\$*"; }
warn() { printf '[warn] %s\\n' "\$*" >&2; }
die() { printf 'error: %s\\n' "\$*" >&2; exit 1; }

fact() {
  local value
  [[ -f \$FACTS ]] || return 1
  value=\$(sed -n "s/^\$1=//p" "\$FACTS" | tail -n1)
  [[ -n \$value ]] || return 1
  printf '%s\\n' "\$value"
}

[[ \$(id -u) -ne 0 ]] || die "run this as your normal user, not root; it calls sudo itself"
command -v git >/dev/null || die "git is missing — 'nix-shell -p git' or fix stage 1 first"

ram_gb=\$(awk '/^MemTotal:/ { printf "%d\\n", \$2 / 1048576 }' /proc/meminfo)

# --- swap ------------------------------------------------------------------
# The teonix flake pins its own nixpkgs and apple-silicon, so this switch does
# rebuild the Asahi kernel. On disk that is fine; without swap an 8 GB Mac OOMs.
#
# The floor is recomputed from RAM rather than trusted from the facts file, so
# a machine written by an older installer still gets enough swap here.
if ((ram_gb <= 8)); then
  swap_floor=16384
elif ((ram_gb <= 16)); then
  swap_floor=12288
else
  swap_floor=8192
fi

if [[ -n \${SWAP_MB:-} ]]; then
  swap_mb=\$SWAP_MB
else
  swap_mb=\$(fact SWAP_MB 2>/dev/null || echo 0)
  ((swap_mb >= swap_floor)) || swap_mb=\$swap_floor
fi

file_mb=0
[[ -f \$SWAPFILE ]] && file_mb=\$(( \$(stat -c %s "\$SWAPFILE") / 1048576 ))

if ((file_mb >= swap_mb)); then
  skip "swap — \$SWAPFILE is already \${file_mb} MiB"
else
  # A too-small file from an earlier run is worse than none: it looks like swap
  # exists while the build still dies. Replace it.
  if ((file_mb > 0)); then
    warn "\$SWAPFILE is only \${file_mb} MiB; growing it to \${swap_mb} MiB"
    sudo swapoff "\$SWAPFILE" 2>/dev/null || true
    sudo rm -f "\$SWAPFILE"
  fi

  free_mb=\$(df --output=avail -BM / | awk 'NR == 2 { gsub(/M/, ""); print }')
  if ((free_mb < swap_mb + 20480)); then
    swap_mb=\$(( free_mb > 25600 ? free_mb - 20480 : 0 ))
    ((swap_mb > 0)) || die "not enough free space on / for a swapfile (\${free_mb} MiB free)"
    warn "trimming the swapfile to \${swap_mb} MiB to leave room for /nix/store"
  fi

  say "creating a \${swap_mb} MiB swapfile at \$SWAPFILE for the kernel build"
  sudo fallocate -l "\${swap_mb}M" "\$SWAPFILE" 2>/dev/null \\
    || sudo dd if=/dev/zero of="\$SWAPFILE" bs=1M count="\$swap_mb" status=progress
  sudo chmod 600 "\$SWAPFILE"
  sudo mkswap "\$SWAPFILE"
  sudo swapon "\$SWAPFILE" || die "swapon \$SWAPFILE failed; the build would OOM without it"
  ok "swap — \${swap_mb} MiB at \$SWAPFILE"
fi

# /proc/swaps separates its columns with tabs, so compare fields, not a prefix.
swap_active() {
  awk -v want="\$1" 'NR > 1 && \$1 == want { hit = 1 } END { exit !hit }' /proc/swaps
}
swap_active "\$SWAPFILE" || sudo swapon "\$SWAPFILE" \\
  || die "swapon \$SWAPFILE failed; the build would OOM without it"

# zram sits at a higher swap priority than a file, so without this a big build
# compresses its pages into RAM — the one place we are short — instead of
# spilling to disk. #applenix does not enable zram, so this only affects the
# stage 1 system we are building from.
if grep -q '^/dev/zram' /proc/swaps; then
  sudo swapoff /dev/zram0 2>/dev/null \\
    && ok "zram — off for the build, so pages reach the real swapfile" \\
    || warn "could not disable zram; the build may still OOM"
fi

# --- repo ------------------------------------------------------------------
# An older bootstrap.sh used to overwrite tracked files in this checkout in
# place. A plain "git pull --ff-only" then refuses, and building anyway meant
# compiling for an hour only to fail on a stale asahi.nix. So: stash anything
# the user changed, then take upstream's tree verbatim.
if [[ -d \$DIR/.git ]]; then
  say "updating \$DIR"
  git -C "\$DIR" fetch --prune origin || warn "git fetch failed; working offline"

  branch=\$(git -C "\$DIR" rev-parse --abbrev-ref HEAD 2>/dev/null || echo main)
  upstream=\$(git -C "\$DIR" rev-parse --abbrev-ref --symbolic-full-name '@{upstream}' 2>/dev/null \\
    || echo "origin/\$branch")

  # hardware-configuration.nix and detected.nix are ours; we rewrite them below.
  dirty=\$(git -C "\$DIR" status --porcelain --untracked-files=no \\
    | awk '{ print \$NF }' \\
    | grep -v -e '^hosts/applenix/hardware-configuration.nix\$' \\
      -e '^hosts/applenix/detected.nix\$' || true)

  if [[ -n \$dirty ]]; then
    warn "local edits to tracked files:"
    printf '         %s\\n' \$dirty >&2
    git -C "\$DIR" stash push -m "applenix-stage2 \$(date -Iseconds)" \\
      && warn "stashed them; recover with: git -C \$DIR stash list" \\
      || warn "stash failed; continuing with a hard reset"
  fi

  git -C "\$DIR" reset --hard "\$upstream" \\
    || die "could not reset \$DIR to \$upstream — fix the checkout by hand, or delete \$DIR and re-run"
  ok "repo — \$DIR at \$(git -C "\$DIR" rev-parse --short HEAD) (\$upstream)"
else
  say "cloning \$REPO into \$DIR"
  mkdir -p "\$(dirname "\$DIR")"
  git clone "\$REPO" "\$DIR"
  ok "repo — cloned to \$DIR"
fi

[[ -f \$DIR/flake.nix ]] || die "\$DIR/flake.nix is missing — wrong repo?"
mkdir -p "\$HOST_DIR"

# Cheap guard against the class of failure that costs a whole kernel build:
# linux-asahi dropped the ignoreConfigErrors argument in release-2026-07-30.
#
# Only .nix files, and only outside comments: the word also appears in this
# installer, in INSTALL.md, and in a comment in asahi.nix explaining why the
# argument is gone. A recursive grep for the bare word matches all three and
# fails a checkout that is perfectly correct.
offenders=""
for nix_file in "\$HOST_DIR"/*.nix; do
  [[ -f \$nix_file ]] || continue
  if sed 's/#.*//' "\$nix_file" | grep -q 'ignoreConfigErrors'; then
    offenders+="\$(basename "\$nix_file") "
  fi
done
if [[ -n \$offenders ]]; then
  die "\$HOST_DIR still passes ignoreConfigErrors to linux-asahi: \$offenders
       (leftover from the retired bootstrap.sh, which overwrote tracked files in place)
       Clean the checkout, then re-run:
         git -C \$DIR fetch origin && git -C \$DIR reset --hard origin/main"
fi

# --- this Mac's real hardware config ---------------------------------------
if [[ -f /etc/nixos/hardware-configuration.nix ]]; then
  sudo cp /etc/nixos/hardware-configuration.nix "\$HOST_DIR/hardware-configuration.nix"
  sudo chown "\$(id -u):\$(id -g)" "\$HOST_DIR/hardware-configuration.nix"
  # Firmware handling belongs to asahi.nix, not to the generated hardware file.
  sed -i '/extractPeripheralFirmware/d' "\$HOST_DIR/hardware-configuration.nix"
  ok "hardware — real UUIDs from this Mac"
else
  warn "no /etc/nixos/hardware-configuration.nix; keeping the repo placeholder"
fi

# --- Asahi peripheral firmware inside the flake ----------------------------
# Keeping firmware.cpio in the flake directory is what lets #applenix
# evaluate purely, with no --impure.
mkdir -p "\$HOST_DIR/firmware"
if [[ -s \$HOST_DIR/firmware/firmware.cpio ]]; then
  skip "firmware — already in the flake"
elif [[ -s /etc/nixos/firmware/firmware.cpio ]]; then
  cp -f /etc/nixos/firmware/firmware.cpio "\$HOST_DIR/firmware/firmware.cpio"
  ok "firmware — copied from /etc/nixos/firmware"
elif [[ -s /boot/vendorfw/firmware.cpio ]]; then
  sudo cp -f /boot/vendorfw/firmware.cpio "\$HOST_DIR/firmware/firmware.cpio"
  sudo chown "\$(id -u):\$(id -g)" "\$HOST_DIR/firmware/firmware.cpio"
  ok "firmware — copied from the ESP"
else
  rmdir "\$HOST_DIR/firmware" 2>/dev/null || true
  warn "no firmware.cpio found; Wi-Fi and the camera will not work"
fi

# --- machine-specific overrides -------------------------------------------
touchbar=\$(fact TOUCHBAR 2>/dev/null || echo no)
chassis=\$(fact CHASSIS 2>/dev/null || echo desktop)
displays=\$(fact DISPLAYS 2>/dev/null || echo unknown)
m1n1=\$(fact M1N1_EXTRA 2>/dev/null || true)
iso_layout=\$(fact ISO_LAYOUT 2>/dev/null || true)

{
  echo "# Generated by /etc/applenix/stage2.sh from \$FACTS."
  echo "# Machine-specific bits detected on this Mac. Safe to commit."
  echo "#"
  echo "# Model:    \$(fact MODEL 2>/dev/null || echo unknown)"
  echo "# Chassis:  \$chassis"
  echo "# Displays: \$displays"
  echo "#           (set the Hyprland monitor and Quickshell shellMonitor to match)"
  echo "{ lib, pkgs, ... }:"
  echo ""
  echo "{"
  if [[ \$touchbar == yes ]]; then
    echo "  hardware.apple.touchBar.enable = true;"
  fi
  if [[ -n \$m1n1 ]]; then
    echo "  boot.m1n1ExtraOptions = \\"\$m1n1\\";"
  fi
  if [[ -n \$iso_layout ]]; then
    echo "  boot.extraModprobeConfig = ''"
    echo "    options hid_apple iso_layout=\$iso_layout"
    echo "  '';"
  fi
  echo "  swapDevices = [ { device = \\"\$SWAPFILE\\"; size = \$swap_mb; } ];"
  echo "}"
} >"\$HOST_DIR/detected.nix"
ok "detected — wrote \$HOST_DIR/detected.nix"

# --- kernel sanity ---------------------------------------------------------
# linux-asahi is in no binary cache, so if its path is not already in the store
# the switch silently turns into a 2h+ compile that OOMs small Macs. asahi.nix
# pins it to apple-silicon's own nixpkgs precisely so it matches the kernel the
# installer copied here; check that held before committing to a long run.
say "checking the Asahi kernel is prebuilt (this is the 2h trap)"
kernel=\$(nix eval --raw "path:\$DIR#nixosConfigurations.applenix.config.boot.kernelPackages.kernel" 2>/dev/null || true)

if [[ -z \$kernel ]]; then
  warn "could not evaluate the kernel path; continuing without the check"
elif nix path-info "\$kernel" >/dev/null 2>&1; then
  ok "kernel — \${kernel##*/} already in the store, nothing to compile"
else
  warn "the Asahi kernel is NOT in the store and no cache has it:"
  warn "  \$kernel"
  warn "Switching now would compile it: 2h+, and it OOMs an 8 GB Mac."
  warn "This means the flake's apple-silicon input no longer matches the ISO"
  warn "this Mac was installed from. Fix the pin rather than build the kernel."
  warn "The kernel this Mac is actually running is:"
  warn "  \$(readlink -f /run/current-system/kernel 2>/dev/null || echo unknown)"
  if [[ \${KERNEL_BUILD_OK:-0} != 1 ]]; then
    die "refusing to start a kernel build; re-run with KERNEL_BUILD_OK=1 to do it anyway"
  fi
  warn "KERNEL_BUILD_OK=1 set — building the kernel as requested"
fi

# --- switch ----------------------------------------------------------------
# max-jobs 1 keeps two heavy derivations from running at once; cores bounds the
# parallelism inside one, which is what actually sets peak memory. rustc in the
# Asahi kernel is the expensive part, so a small Mac must not use every core.
if [[ -n \${BUILD_CORES:-} ]]; then
  cores=\$BUILD_CORES
elif cores=\$(fact BUILD_CORES 2>/dev/null); then
  :
elif ((ram_gb <= 8)); then
  cores=2
elif ((ram_gb <= 16)); then
  cores=4
else
  cores=0 # 0 = all
fi
swap_active_mb=\$(awk 'NR > 1 { total += \$3 } END { printf "%d\\n", total / 1024 }' /proc/swaps)

say ""
say "switching to #applenix; the Asahi kernel builds here, so expect a long run"
say "  RAM \${ram_gb} GiB, swap \${swap_active_mb} MiB, max-jobs 1, cores \$cores"
say "  if this still gets killed, re-run with: BUILD_CORES=1 \$0"
say "  (use tmux if you are over ssh)"
say ""
cd "\$DIR"
sudo nixos-rebuild switch --flake "path:.#applenix" \\
  --option max-jobs 1 \\
  --option cores "\$cores"

say ""
ok "stage 2 complete"
say "reboot, then pick Hyprland at the display manager"
EOF
}

# ---------------------------------------------------------- dispatcher ------

run_step() {
  local step=$1 fn="step_${1}" probe="probe_${1}"

  [[ $(type -t "$fn") == function ]] || die "unknown step: $step"

  if [[ ${FORCE:-0} != 1 ]] && "$probe" 2>/dev/null; then
    skip "$step"
    return 0
  fi

  CURRENT_STEP=$step
  runmsg "$step"
  "$fn"
  CURRENT_STEP=""
}

cmd_status() {
  local step state detail

  say "${SELF} v${VERSION}"
  say "  facts   $FACTS"
  say "  target  $TARGET"
  say "  disk    $(fact_or DISK '(not detected yet)')"
  say "  root    $(fact_or ROOT_PART '(not chosen yet)')"
  say ""
  printf '%-10s %-8s %s\n' STEP STATE DETAIL

  for step in "${STEPS[@]}"; do
    detail=""
    case $step in
      detect) detail="$(fact_or MODEL '-')" ;;
      net) probe_net && detail="online" || detail="offline" ;;
      disk) detail="$(fact_or ROOT_PART '-')" ;;
      format)
        detail=$(blkid -o value -s TYPE "$(fact_or ROOT_PART /dev/null)" 2>/dev/null || echo "-")
        ;;
      mount)
        findmnt -M "$TARGET" >/dev/null 2>&1 \
          && detail="$(findmnt -no SOURCE "$TARGET") + $(findmnt -no SOURCE "$TARGET/boot" 2>/dev/null || echo 'no esp')" \
          || detail="not mounted"
        ;;
      firmware) [[ -s $FW_DIR/firmware.cpio ]] && detail="present" || detail="missing" ;;
      config) [[ -f $NIXOS_DIR/configuration.nix ]] && detail="$NIXOS_DIR" || detail="-" ;;
      install) probe_install && detail="system profile exists" || detail="-" ;;
      stage2) [[ -x $STAGE2 ]] && detail="${STAGE2#"${TARGET%/}"}" || detail="-" ;;
      summary) detail="-" ;;
    esac

    if "probe_${step}" 2>/dev/null; then
      state="done"
    else
      state="pending"
    fi
    printf '%-10s %-8s %s\n' "$step" "$state" "$detail"
  done
}

usage() {
  cat <<EOF
${SELF} v${VERSION} — stage 1 installer for any Apple Silicon Mac

Usage, as root from the nixos-apple-silicon USB installer:

  ${CURL_CMD}

  … all              run every pending step (default)
  … status           show the live checklist
  … list             print step names
  … run STEP [STEP]  run only these steps
  … help             this text

Steps: ${STEPS[*]}

Environment:
  YES=1            skip confirmation prompts
  FORCE=1          redo steps even when they look finished
  FORMAT=1         allow mkfs over an existing filesystem
  DISK=/dev/…      target disk (default: the disk holding the Asahi ESP)
  ROOT_PART=/dev/… use this partition instead of creating one
  TARGET_USER=…    first user (default teodor)
  TARGET_HOST=…    hostname (default applenix)
  TOUCHBAR=yes|no  override Touch Bar detection
  ISO_LAYOUT=0|1   hid_apple iso_layout, if \` and < are swapped
  M1N1_EXTRA=…     boot.m1n1ExtraOptions, for Mac mini display quirks
  SWAP_SIZE=MiB    swap the stage 2 helper creates (default from RAM)
  BUILD_CORES=N    cores per derivation in stage 2; lower it if the build OOMs
  KERNEL_BUILD_OK=1 let stage 2 compile the Asahi kernel instead of refusing
  PKGS_SYSTEM=…    set if the ISO was cross-built and the kernel rebuilds
  CHARGE_LIMIT=…   battery charge ceiling on laptops (default 80)
  TEONIX_REPO=…    repo stage 2 clones
  TEONIX_DIR=…     where stage 2 clones it

To resume after any failure, just run the same command again.
EOF
}

main() {
  local step

  case ${1:-all} in
    help | -h | --help)
      usage
      ;;
    list)
      printf '%s\n' "${STEPS[@]}"
      ;;
    status)
      cmd_status
      ;;
    run)
      need_root
      shift
      (($#)) || die "run needs at least one step name"
      for step in "$@"; do
        run_step "$step"
      done
      ;;
    all)
      need_root
      say "${SELF} v${VERSION}"
      say ""
      for step in "${STEPS[@]}"; do
        run_step "$step"
      done
      ;;
    *)
      # Bare step names are accepted too: … mount firmware
      need_root
      for step in "$@"; do
        run_step "$step"
      done
      ;;
  esac
}

main "$@"
